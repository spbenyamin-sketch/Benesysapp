// One HTML-table builder for every report PDF. A report supplies its title,
// period line, columns, rows and totals; this turns them into a printable page
// (expo-print on the phone, the browser's print dialog on web).
//
// Pure — no expo imports — so the escaping and the totals can be unit tested.
// Every piece of text goes through the one escaper in utils/html: a party called
// "Raj & Co <Chennai>" must print as itself, not as broken markup.

import { escapeHtml as esc, htmlMoney } from '@/utils/html';

/** A cell: text, a number, or blank. */
export type ReportCell = string | number | null | undefined;

export interface ReportColumn {
  header: string;
  /** Numbers in this column are PAISE and print as ₹1,234.00. */
  money?: boolean;
}

export interface ReportTable {
  /** Heading above the table — only printed when the report has several. */
  name?: string;
  columns: ReportColumn[];
  rows: ReportCell[][];
  /** Bold last row, e.g. ['TOTAL', '', 12345]. */
  totals?: ReportCell[];
}

export interface ReportDoc {
  business: string;
  gstin?: string | null;
  title: string;
  /** "Period: 1 Apr 2026 to 30 Apr 2026", "As of: …". */
  subtitle?: string;
  tables: ReportTable[];
}

function cell(v: ReportCell, col: ReportColumn | undefined): { html: string; num: boolean } {
  if (v === null || v === undefined || v === '') return { html: '', num: false };
  if (typeof v === 'number') {
    if (col?.money) return { html: esc(htmlMoney(v)), num: true };
    return { html: esc(Number.isFinite(v) ? String(v) : ''), num: true };
  }
  return { html: esc(v), num: false };
}

function rowHtml(values: ReportCell[], columns: ReportColumn[], tag: 'td' | 'th' = 'td'): string {
  return `<tr>${columns
    .map((col, i) => {
      const c = cell(values[i], col);
      return `<${tag}${c.num ? ' class="num"' : ''}>${c.html}</${tag}>`;
    })
    .join('')}</tr>`;
}

function tableHtml(t: ReportTable, showName: boolean): string {
  const head = t.columns
    .map((c) => `<th${c.money ? ' class="num"' : ''}>${esc(c.header)}</th>`)
    .join('');
  const body = t.rows.length
    ? t.rows.map((r) => rowHtml(r, t.columns)).join('')
    : `<tr><td class="empty" colspan="${t.columns.length}">Nothing to show.</td></tr>`;
  const foot = t.totals ? `<tfoot>${rowHtml(t.totals, t.columns)}</tfoot>` : '';
  return `${showName && t.name ? `<h2>${esc(t.name)}</h2>` : ''}
    <table><thead><tr>${head}</tr></thead><tbody>${body}</tbody>${foot}</table>`;
}

/** The whole printable page for one report. */
export function buildReportHtml(doc: ReportDoc): string {
  const many = doc.tables.length > 1;
  // Wide reports (stock, invoice lists) get a smaller type so they fit portrait.
  const widest = Math.max(0, ...doc.tables.map((t) => t.columns.length));
  const fontSize = widest > 7 ? 9 : 11;
  return `<!doctype html><html><head><meta charset="utf-8" />
  <title>${esc(doc.title)}</title>
  <style>
    @page { margin: 12mm; }
    * { font-family: -apple-system, Roboto, Arial, sans-serif; }
    body { color: #111; padding: 8px; font-size: ${fontSize}px; }
    .biz { font-size: 18px; font-weight: 700; }
    .muted { color: #666; }
    .doc { font-size: 15px; font-weight: 700; color: #208AEF; margin-top: 6px; }
    h2 { font-size: 13px; margin: 18px 0 0; }
    table { width: 100%; border-collapse: collapse; margin-top: 8px; }
    th, td { border-bottom: 1px solid #e5e5e5; padding: 5px 4px; text-align: left; vertical-align: top; }
    th { background: #f4f8fe; font-size: ${fontSize - 1}px; text-transform: uppercase; color: #555; }
    .num { text-align: right; white-space: nowrap; }
    tfoot td { font-weight: 700; border-bottom: none; border-top: 1px solid #999; }
    .empty { color: #999; text-align: center; }
    thead { display: table-header-group; }
    tr { page-break-inside: avoid; }
    .foot { margin-top: 24px; color: #999; font-size: 10px; text-align: center; }
  </style></head><body>
    <div class="biz">${esc(doc.business)}</div>
    ${doc.gstin ? `<div class="muted">GSTIN: ${esc(doc.gstin)}</div>` : ''}
    <div class="doc">${esc(doc.title)}</div>
    ${doc.subtitle ? `<div class="muted">${esc(doc.subtitle)}</div>` : ''}
    ${doc.tables.map((t) => tableHtml(t, many)).join('')}
    <div class="foot">Generated by the billing app · This is a computer-generated report.</div>
  </body></html>`;
}
