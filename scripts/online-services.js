// Online mode: which of the app's services the web app reaches over the network.
//
// For every exported `async function` in these modules/<name>/service.ts files,
// this writes two things that must never drift apart:
//   web/services/<name>.ts         — what `@/modules/<name>/service` means on web
//                                    (metro.config.js swaps it in): the module's
//                                    own sync helpers, plus a network call in
//                                    place of each async function;
//   server/src/rpc/registry.ts     — the allowlist the server will run, which
//                                    is those same functions and nothing else.
//
//   node scripts/online-services.js         regenerate
//   node scripts/online-services.js --check exit 1 if the files are stale
//
// A test (web/__tests__/onlineServices.test.ts) runs the check, so adding a
// service function without regenerating fails `npm test`.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

/** Modules whose data lives in the shop's database. auth/backup/license stay on the device. */
const MODULES = [
  'bankAccounts',
  'expenses',
  'invoices',
  'items',
  'parties',
  'payments',
  'pos',
  'reports',
  'settings',
  'tally',
];

function asyncFunctionsOf(moduleName) {
  const source = fs.readFileSync(path.join(ROOT, 'modules', moduleName, 'service.ts'), 'utf8');
  return [...source.matchAll(/^export async function (\w+)/gm)].map((m) => m[1]);
}

const HEADER = '// GENERATED by scripts/online-services.js — do not edit by hand.\n';

function renderStub(moduleName) {
  const fns = asyncFunctionsOf(moduleName);
  const lines = [
    HEADER,
    `// On web, every import of modules/${moduleName}/service resolves here instead`,
    '// (metro.config.js). Its synchronous helpers and constants are the real ones;',
    '// each async function runs on the server against the signed-in shop.',
    '',
    `import type * as local from '@/modules/${moduleName}/service';`,
    "import { rpc } from '@/web/rpc';",
    '',
    `export * from '../../modules/${moduleName}/service';`,
    '',
    ...fns.map(
      (fn) => `export const ${fn}: typeof local.${fn} = rpc('${moduleName}', '${fn}');`,
    ),
    '',
  ];
  return lines.join('\n');
}

function renderRegistry() {
  const lines = [
    HEADER,
    '// The only functions POST /api/rpc/:module/:fn will run. Everything here is an',
    "// exported async function of the app's own service module, executed unchanged",
    "// inside the signed-in shop's transaction (see routes/rpc.ts).",
    '',
    ...MODULES.map((m) => `import * as ${m} from '@/modules/${m}/service';`),
    '',
    'export type RpcFunction = (...args: any[]) => Promise<unknown>;',
    '',
    'export const registry: Record<string, Record<string, RpcFunction>> = {',
    ...MODULES.flatMap((m) => [
      `  ${m}: {`,
      ...asyncFunctionsOf(m).map((fn) => `    ${fn}: ${m}.${fn},`),
      '  },',
    ]),
    '};',
    '',
  ];
  return lines.join('\n');
}

function outputs() {
  const files = MODULES.map((m) => [path.join(ROOT, 'web', 'services', `${m}.ts`), renderStub(m)]);
  files.push([path.join(ROOT, 'server', 'src', 'rpc', 'registry.ts'), renderRegistry()]);
  return files;
}

/** Files whose content on disk differs from what would be generated. */
function staleFiles() {
  return outputs()
    .filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content)
    .map(([file]) => path.relative(ROOT, file));
}

function write() {
  for (const [file, content] of outputs()) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}

module.exports = { MODULES, staleFiles };

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const stale = staleFiles();
    if (stale.length) {
      console.error(`Stale, run node scripts/online-services.js:\n  ${stale.join('\n  ')}`);
      process.exit(1);
    }
  } else {
    write();
    console.log('online services regenerated');
  }
}
