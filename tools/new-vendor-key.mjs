// Mint a fresh vendor signing keypair.
//
//   node tools/new-vendor-key.mjs
//
// The SECRET half is written to tools/vendor-private-key.txt (gitignored) and
// never printed — back that file up somewhere safe and offline. Lose it and you
// cannot issue or renew a single licence; leak it and anyone can.
//
// The PUBLIC half is written into modules/license/publicKey.ts and ships inside
// the APK, which is the whole point: the app can check a licence but can never
// create one.
//
// Running this again invalidates every licence file ever issued. Only do it if
// the private key was lost or leaked — then rebuild the APK and re-issue to
// every client.

import { writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ed from '@noble/ed25519';
import { sha512 } from '@noble/hashes/sha2.js';

ed.hashes.sha512 = sha512;

const here = dirname(fileURLToPath(import.meta.url));
const PRIVATE_PATH = join(here, 'vendor-private-key.txt');
const PUBLIC_PATH = join(here, '..', 'modules', 'license', 'publicKey.ts');

if (existsSync(PRIVATE_PATH) && !process.argv.includes('--force')) {
  console.error(
    `Refusing to overwrite ${PRIVATE_PATH}.\n` +
      'Every licence ever issued is signed with the key in that file.\n' +
      'Pass --force only if you really mean to invalidate all of them.',
  );
  process.exit(1);
}

const toHex = (bytes) => Buffer.from(bytes).toString('hex');

const secretKey = ed.utils.randomSecretKey();
const publicKey = ed.getPublicKey(secretKey);

writeFileSync(
  PRIVATE_PATH,
  `${toHex(secretKey)}\n\n` +
    '# Billing App vendor signing key (Ed25519, hex).\n' +
    '# Paste the first line into tools/keygen.html when it asks for the vendor key.\n' +
    '# Keep this file OFF any client machine and OUT of version control.\n',
  'utf8',
);

writeFileSync(
  PUBLIC_PATH,
  `// The vendor's Ed25519 PUBLIC key — generated by tools/new-vendor-key.mjs.
//
// This ships inside the APK on purpose. It can verify a licence file and it
// cannot create one, so pulling it out of a decompiled bundle buys an attacker
// nothing. The private half never leaves the vendor's machine.
//
// Regenerating the pair invalidates every licence already issued.
export const VENDOR_PUBLIC_KEY = '${toHex(publicKey)}';
`,
  'utf8',
);

console.log('Vendor keypair written.');
console.log(`  secret → ${PRIVATE_PATH}  (back this up, never share it)`);
console.log(`  public → ${PUBLIC_PATH}   (committed, ships in the APK)`);
console.log(`\nPublic key: ${toHex(publicKey)}`);
